import { BookOpenText, Check, ChevronRight, Plus, RefreshCcw, Save, Search, Sparkles, Trash2 } from "lucide-react";
import { useEffect, useMemo, useRef, useState } from "react";
import type { Bible, GlossaryEntry, JobStatus, PronounRule } from "../types";
import { RUNNING } from "../types";
import { Button, IconButton, TextInput, cx } from "./ui";

const EMPTY: Bible = { synopsis_and_tone: "", speaker_pronoun_rules: [], glossary: [] };

function same(a: Bible | null, b: Bible | null) {
  return JSON.stringify(a ?? EMPTY) === JSON.stringify(b ?? EMPTY);
}

export function BibleDrawer({
  open,
  onToggle,
  bible,
  status,
  approved,
  busy,
  onSave,
  onApprove,
  onRerun,
  qaEnabled,
}: {
  open: boolean;
  onToggle: () => void;
  bible: Bible | null;
  status: JobStatus | null;
  approved: boolean;
  busy: boolean;
  onSave: (b: Bible) => Promise<void>;
  onApprove: (b: Bible) => Promise<void>;
  onRerun: (stage: 2 | 3, b: Bible, dirty: boolean) => Promise<void>;
  qaEnabled: boolean;
}) {
  // `base` is the server version the local draft was last synced from.
  const [base, setBase] = useState<Bible | null>(bible);
  const [draft, setDraft] = useState<Bible>(bible ?? EMPTY);
  const [query, setQuery] = useState("");
  const dirty = !same(draft, base);
  const running = status !== null && RUNNING.has(status);
  const locked = running || busy;

  // Follow server updates (Stage 1 result, saves) unless the user has unsaved edits.
  const baseRef = useRef(base);
  baseRef.current = base;
  useEffect(() => {
    const prev = baseRef.current;
    if (same(bible, prev)) return;
    setDraft((d) => (same(d, prev) ? (bible ?? EMPTY) : d));
    setBase(bible);
  }, [bible]);

  const glossary = useMemo(() => {
    const q = query.trim().toLowerCase();
    return draft.glossary
      .map((g, i) => ({ g, i }))
      .filter(({ g }) => !q || `${g.source_term} ${g.target_term} ${g.notes}`.toLowerCase().includes(q));
  }, [draft.glossary, query]);

  const setRule = (i: number, patch: Partial<PronounRule>) =>
    setDraft((d) => ({ ...d, speaker_pronoun_rules: d.speaker_pronoun_rules.map((r, j) => (j === i ? { ...r, ...patch } : r)) }));
  const setTerm = (i: number, patch: Partial<GlossaryEntry>) =>
    setDraft((d) => ({ ...d, glossary: d.glossary.map((g, j) => (j === i ? { ...g, ...patch } : g)) }));

  if (!open) {
    return (
      <button
        type="button"
        onClick={onToggle}
        className="hidden w-10 shrink-0 flex-col items-center gap-2 border-l border-line bg-panel py-4 text-muted transition hover:bg-panel-2 hover:text-ink md:flex"
        aria-label="Open Translation Bible"
        title="Translation Bible & Glossary"
      >
        <BookOpenText size={17} />
        <span className="text-[11px] font-medium tracking-wide [writing-mode:vertical-rl]">Translation Bible</span>
        {bible && !approved && <span className="h-2 w-2 rounded-full bg-warn" />}
      </button>
    );
  }

  return (
    <aside className="fixed inset-0 z-30 flex w-full flex-col border-l border-line bg-panel md:static md:z-auto md:w-[440px] md:shrink-0">
      <div className="flex items-center gap-2 border-b border-line px-4 py-3">
        <BookOpenText size={17} className="text-accent" />
        <div className="min-w-0 flex-1">
          <h2 className="text-sm font-semibold text-ink">Translation Bible &amp; Glossary</h2>
          <p className="text-[11px] text-muted">
            {bible ? (running ? "Read-only while the pipeline runs — pause to edit." : "Edits apply to Stage 2 & 3 runs.") : "Generated by Stage 1."}
          </p>
        </div>
        <IconButton label="Collapse drawer" onClick={onToggle}>
          <ChevronRight size={17} />
        </IconButton>
      </div>

      {!bible ? (
        <div className="flex flex-1 items-center justify-center p-8 text-center text-sm text-muted">
          {status === "bible_running" ? "Extracting the Bible from the transcript…" : "Start the pipeline to extract the Translation Bible."}
        </div>
      ) : (
        <div className={cx("flex-1 space-y-5 overflow-y-auto p-4", locked && "opacity-80")}>
          <section>
            <label htmlFor="bible-tone" className="mb-1.5 block text-xs font-semibold uppercase tracking-wider text-muted">
              Synopsis &amp; tone
            </label>
            <textarea
              id="bible-tone"
              value={draft.synopsis_and_tone}
              disabled={locked}
              onChange={(e) => setDraft({ ...draft, synopsis_and_tone: e.target.value })}
              rows={6}
              className="w-full resize-y rounded-lg border border-line bg-panel-2 p-2.5 text-sm leading-relaxed text-ink focus:border-accent focus:outline-none focus:ring-2 focus:ring-accent/25"
            />
          </section>

          <section>
            <div className="mb-1.5 flex items-center justify-between">
              <span className="text-xs font-semibold uppercase tracking-wider text-muted">
                Speaker &amp; pronoun rules ({draft.speaker_pronoun_rules.length})
              </span>
              <Button
                size="sm"
                variant="ghost"
                icon={<Plus size={13} />}
                disabled={locked}
                onClick={() => setDraft({ ...draft, speaker_pronoun_rules: [...draft.speaker_pronoun_rules, { speakers: "", rule: "" }] })}
              >
                Add
              </Button>
            </div>
            <div className="space-y-2">
              {draft.speaker_pronoun_rules.map((r, i) => (
                <div key={i} className="rounded-lg border border-line bg-panel-2 p-2">
                  <div className="flex items-center gap-1.5">
                    <TextInput
                      aria-label="Speakers"
                      className="h-8 bg-panel text-xs font-medium"
                      placeholder="Speaker → listener"
                      value={r.speakers}
                      disabled={locked}
                      onChange={(e) => setRule(i, { speakers: e.target.value })}
                    />
                    <IconButton
                      label="Remove rule"
                      className="h-8 w-8 hover:text-danger"
                      disabled={locked}
                      onClick={() => setDraft({ ...draft, speaker_pronoun_rules: draft.speaker_pronoun_rules.filter((_, j) => j !== i) })}
                    >
                      <Trash2 size={14} />
                    </IconButton>
                  </div>
                  <textarea
                    aria-label="Rule"
                    rows={2}
                    placeholder="e.g. Always formal 'Aap'"
                    value={r.rule}
                    disabled={locked}
                    onChange={(e) => setRule(i, { rule: e.target.value })}
                    className="mt-1.5 w-full resize-y rounded-md border border-line bg-panel p-2 text-xs text-ink focus:border-accent focus:outline-none"
                  />
                </div>
              ))}
            </div>
          </section>

          <section>
            <div className="mb-1.5 flex items-center justify-between">
              <span className="text-xs font-semibold uppercase tracking-wider text-muted">Glossary ({draft.glossary.length})</span>
              <Button
                size="sm"
                variant="ghost"
                icon={<Plus size={13} />}
                disabled={locked}
                onClick={() => setDraft({ ...draft, glossary: [{ source_term: "", target_term: "", notes: "" }, ...draft.glossary] })}
              >
                Add term
              </Button>
            </div>
            {draft.glossary.length > 8 && (
              <div className="relative mb-2">
                <Search size={13} className="pointer-events-none absolute left-2.5 top-1/2 -translate-y-1/2 text-muted" />
                <TextInput className="h-8 pl-7 text-xs" placeholder="Filter glossary" value={query} onChange={(e) => setQuery(e.target.value)} />
              </div>
            )}
            <div className="overflow-hidden rounded-lg border border-line">
              <div className="grid grid-cols-[1fr_1fr_28px] gap-px bg-line text-[10px] font-semibold uppercase tracking-wider text-muted">
                <div className="bg-panel-2 px-2 py-1.5">Source</div>
                <div className="bg-panel-2 px-2 py-1.5">Target</div>
                <div className="bg-panel-2" />
              </div>
              {glossary.map(({ g, i }) => (
                <div key={i} className="border-t border-line">
                  <div className="grid grid-cols-[1fr_1fr_28px]">
                    <input
                      aria-label="Source term"
                      className="min-w-0 border-r border-line bg-panel px-2 py-1.5 text-xs text-ink focus:bg-panel-2 focus:outline-none"
                      value={g.source_term}
                      disabled={locked}
                      onChange={(e) => setTerm(i, { source_term: e.target.value })}
                    />
                    <input
                      aria-label="Target term"
                      className="min-w-0 border-r border-line bg-panel px-2 py-1.5 text-xs font-medium text-ink focus:bg-panel-2 focus:outline-none"
                      value={g.target_term}
                      disabled={locked}
                      onChange={(e) => setTerm(i, { target_term: e.target.value })}
                    />
                    <button
                      type="button"
                      aria-label="Remove term"
                      className="flex items-center justify-center bg-panel text-muted hover:text-danger disabled:opacity-40"
                      disabled={locked}
                      onClick={() => setDraft({ ...draft, glossary: draft.glossary.filter((_, j) => j !== i) })}
                    >
                      <Trash2 size={12} />
                    </button>
                  </div>
                  <input
                    aria-label="Notes"
                    placeholder="notes"
                    className="w-full border-t border-dashed border-line bg-panel px-2 py-1 text-[11px] text-muted focus:bg-panel-2 focus:outline-none"
                    value={g.notes}
                    disabled={locked}
                    onChange={(e) => setTerm(i, { notes: e.target.value })}
                  />
                </div>
              ))}
              {glossary.length === 0 && <div className="border-t border-line p-3 text-center text-xs text-muted">No terms.</div>}
            </div>
          </section>
        </div>
      )}

      {bible && (
        <div className="space-y-2 border-t border-line bg-panel-2/40 p-3">
          {status === "awaiting_review" ? (
            <Button variant="primary" className="w-full" icon={<Check size={15} />} disabled={busy} onClick={() => onApprove(draft)}>
              {dirty ? "Save, approve & start Stage 2" : "Approve & start Stage 2"}
            </Button>
          ) : (
            <Button className="w-full" icon={<Save size={14} />} disabled={!dirty || locked} onClick={() => onSave(draft)}>
              {dirty ? "Save Bible" : "Saved"}
            </Button>
          )}
          {status !== "awaiting_review" && (
            <div className="grid grid-cols-2 gap-2">
              <Button size="sm" icon={<RefreshCcw size={13} />} disabled={locked} onClick={() => onRerun(2, draft, dirty)}>
                {qaEnabled ? "Re-run Stage 2 + 3" : "Re-run Stage 2"}
              </Button>
              <Button size="sm" variant="qa" icon={<Sparkles size={13} />} disabled={locked} onClick={() => onRerun(3, draft, dirty)}>
                Re-run Stage 3
              </Button>
            </div>
          )}
        </div>
      )}
    </aside>
  );
}
